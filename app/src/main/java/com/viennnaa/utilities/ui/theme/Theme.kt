/**
 * Colors mini apps need that Material's scheme has no slot for.
 */
data class ExtendedColors(
    val yes: Color,
    val no: Color,
)

val LocalExtendedColors = staticCompositionLocalOf {
    ExtendedColors(yes = YesLight, no = NoLight)
}

/** Shorthand for [LocalExtendedColors], read the same way as `MaterialTheme.colorScheme`. */
val extendedColors: ExtendedColors
    @Composable get() = LocalExtendedColors.current

@Composable
fun UtilitiesTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    // Dynamic color is available on Android 12+.
    dynamicColor: Boolean = true,
    content: @Composable () -> Unit,
) {
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }

        darkTheme -> DarkColors
        else -> LightColors
    }

    val extended = if (darkTheme) {
        ExtendedColors(yes = YesDark, no = NoDark)
    } else {
        ExtendedColors(yes = YesLight, no = NoLight)
    }

    CompositionLocalProvider(LocalExtendedColors provides extended) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = UtilitiesTypography,
            content = content,
        )
    }
}
